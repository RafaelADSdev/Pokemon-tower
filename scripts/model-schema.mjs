import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const executable = join(dirname(require.resolve("gltfjsx/package.json")), "cli.js");
const project = fileURLToPath(new URL("../", import.meta.url));

export async function writeModelSchema(definitions) {
  const entries = [];
  for (const { visual } of definitions) {
    const asset = `public/models/${visual}.glb`;
    const jsx = execFileSync(process.execPath, [executable, asset, "--types", "--keepnames", "--console"], {
      cwd: project,
      encoding: "utf8",
    });
    const nodes = jsx.split(/nodes: \{\r?\n/)[1]?.split(/\r?\n  \}/)[0]?.trim();
    const mesh = nodes?.match(/^(?:([a-z][a-z\d]*)|\[['"]([a-z][a-z\d-]*)['"]\]): THREE\.Mesh$/i);
    const name = mesh?.[1] ?? mesh?.[2];
    if (!name) throw new Error(`${asset} must have one typed mesh. gltfjsx returned:\n${jsx}`);
    entries.push(`  "${asset.slice(6)}": "${name}",`);
  }

  const source = [
    "// Generated by scripts/export-models.mjs from gltfjsx's typed mesh nodes.",
    "export const modelNodeByPath = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
  await writeFile(new URL("../src/render/models/generatedNodes.ts", import.meta.url), source);
}
